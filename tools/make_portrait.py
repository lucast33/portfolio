"""Turn a photo into the 1-bit dithered portrait used on about.html.

    python tools/make_portrait.py                       # uses assets/portrait-source.jpeg
    python tools/make_portrait.py photo.jpg --crop 190 205 790 905 --size 120 140

Writes assets/portrait.js (window.PORTRAIT = {w, h, bits}) plus a preview PNG.
The bits are packed 1 bit per pixel, row-major, most significant bit first.
Requires Pillow and numpy.
"""
import argparse
import base64
from pathlib import Path

import numpy as np
from PIL import Image, ImageFilter, ImageOps

ROOT = Path(__file__).resolve().parent.parent


def tone_map(img, radius, detail, base_k, gamma):
    """Local contrast: squash the overall range, boost fine detail.
    Keeps a flash-lit face from blowing out while dark areas keep their shapes."""
    img = ImageOps.autocontrast(img, cutoff=0.5)
    a = (np.asarray(img, dtype=np.float64) / 255.0) ** gamma
    blur = Image.fromarray((a * 255).astype(np.uint8)).filter(ImageFilter.GaussianBlur(radius))
    base = np.asarray(blur, dtype=np.float64) / 255.0
    return np.clip(0.5 + detail * (a - base) + base_k * (base - 0.5), 0, 1)


def atkinson(a):
    """Atkinson dithering (the original Macintosh look): crisp, high-contrast."""
    a = a.copy()
    h, w = a.shape
    out = np.zeros((h, w), dtype=np.uint8)
    for y in range(h):
        for x in range(w):
            old = a[y, x]
            new = 1.0 if old >= 0.5 else 0.0
            out[y, x] = int(new)
            err = (old - new) / 8
            for dx, dy in ((1, 0), (2, 0), (-1, 1), (0, 1), (1, 1), (0, 2)):
                xx, yy = x + dx, y + dy
                if 0 <= xx < w and yy < h:
                    a[yy, xx] += err
    return out


def main():
    p = argparse.ArgumentParser()
    p.add_argument('src', nargs='?', default=str(ROOT / 'assets' / 'portrait-source.jpeg'))
    p.add_argument('--crop', nargs=4, type=int, default=[190, 205, 790, 905], metavar=('L', 'T', 'R', 'B'))
    p.add_argument('--size', nargs=2, type=int, default=[120, 140], metavar=('W', 'H'))
    p.add_argument('--out', default=str(ROOT / 'assets' / 'portrait.js'))
    args = p.parse_args()

    w, h = args.size
    img = Image.open(args.src).convert('L').crop(tuple(args.crop)).resize((w, h), Image.LANCZOS)
    bits = atkinson(tone_map(img, radius=6, detail=2.2, base_k=0.9, gamma=1.15))

    packed = np.packbits(bits.flatten()).tobytes()
    b64 = base64.b64encode(packed).decode('ascii')
    Path(args.out).write_text(
        '/* generated by tools/make_portrait.py from %s, do not edit by hand */\n'
        'window.PORTRAIT = { w: %d, h: %d, bits: "%s" };\n' % (Path(args.src).name, w, h, b64),
        encoding='utf-8',
    )
    preview = ROOT / 'tools' / 'portrait-preview.png'
    Image.fromarray(bits * 255).resize((w * 3, h * 3), Image.NEAREST).save(preview)
    print('wrote %s (%d bytes of bits) and %s' % (args.out, len(packed), preview))


if __name__ == '__main__':
    main()
